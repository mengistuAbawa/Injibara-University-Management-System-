CREATE TABLE IF NOT EXISTS cost_sharing_forms (
  form_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  student_type varchar(20) NOT NULL DEFAULT 'department'
    CHECK (student_type IN ('fresh', 'department')),
  full_name varchar(150) NOT NULL,
  sex varchar(10) NOT NULL CHECK (sex IN ('Male', 'Female')),
  date_of_birth date,
  mother_full_name varchar(150),
  region varchar(100),
  zone varchar(100),
  woreda varchar(100),
  city_town varchar(100),
  phone_number varchar(30),
  pobox varchar(50),
  highschool_name varchar(150),
  highschool_completion_date date,
  college_faculty varchar(150),
  department varchar(150),
  year_of_attendance integer,
  current_year integer,
  withdrawn_date date,
  withdrawn_semester varchar(30),
  is_transferred boolean NOT NULL DEFAULT FALSE,
  prev_university_name varchar(150),
  prev_department varchar(150),
  date_of_transfer date,
  demand_in_kind varchar(10) NOT NULL DEFAULT 'none' CHECK (demand_in_kind IN ('food', 'boarding', 'both', 'none')),
  demand_in_cash varchar(10) NOT NULL DEFAULT 'none' CHECK (demand_in_cash IN ('food', 'boarding', 'both', 'none')),
  calculated_fee numeric(10,2) NOT NULL DEFAULT 17695.95,
  advance_paid boolean NOT NULL DEFAULT FALSE,
  advance_discount numeric(5,2) NOT NULL DEFAULT 0,
  receipt_no varchar(100),
  signed_by_student boolean NOT NULL DEFAULT FALSE,
  signed_by_head boolean NOT NULL DEFAULT FALSE,
  status varchar(20) NOT NULL DEFAULT 'Draft',
  rejection_reason varchar(500),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE cost_sharing_forms ADD COLUMN IF NOT EXISTS student_type varchar(20) NOT NULL DEFAULT 'department';
ALTER TABLE cost_sharing_forms ADD COLUMN IF NOT EXISTS rejection_reason varchar(500);
ALTER TABLE cost_sharing_forms ADD COLUMN IF NOT EXISTS signed_by_student boolean NOT NULL DEFAULT FALSE;
ALTER TABLE cost_sharing_forms ADD COLUMN IF NOT EXISTS signed_by_head boolean NOT NULL DEFAULT FALSE;
