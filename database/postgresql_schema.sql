-- Empty PostgreSQL schema for the INU Portal application.
-- Run this script while connected to the target database (for example, university_db).
-- It creates tables and indexes only; it does not migrate or seed application data.

BEGIN;

CREATE TABLE IF NOT EXISTS colleges (
  college_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  college_name varchar(120) NOT NULL UNIQUE,
  college_code varchar(20) NOT NULL UNIQUE,
  dean_user_id integer,
  dean_name varchar(120),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS system_settings (
  id integer PRIMARY KEY,
  current_academic_year varchar(10) NOT NULL DEFAULT '2025/2026',
  current_semester varchar(10) NOT NULL DEFAULT 'I'
    CHECK (current_semester IN ('I', 'II', 'Summer')),
  registration_open boolean NOT NULL DEFAULT TRUE,
  field_selection_open boolean NOT NULL DEFAULT FALSE,
  field_selection_start timestamp,
  field_selection_end timestamp
);

CREATE TABLE IF NOT EXISTS users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(40) UNIQUE,
  avatar_path varchar(255),
  first_name varchar(50),
  last_name varchar(50),
  email varchar(100) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  role varchar(20) NOT NULL
    CHECK (role IN ('admin', 'registrar', 'instructor', 'student', 'finance', 'dean')),
  college_id integer REFERENCES colleges(college_id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS access_requests (
  request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role varchar(20) NOT NULL
    CHECK (role IN ('student', 'registrar', 'instructor', 'head', 'admin', 'finance', 'dean')),
  email varchar(100) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  applicant_data text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  submitted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by integer REFERENCES users(user_id) ON DELETE SET NULL,
  reviewed_at timestamp,
  registrar_note text
);

CREATE TABLE IF NOT EXISTS departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name varchar(100) NOT NULL,
  department_code varchar(10) NOT NULL UNIQUE,
  faculty varchar(100),
  college_id integer REFERENCES colleges(college_id) ON DELETE SET NULL,
  capacity integer NOT NULL DEFAULT 50,
  min_score numeric(7,2) NOT NULL DEFAULT 0,
  is_available_for_selection boolean NOT NULL DEFAULT TRUE,
  hod_user_id integer REFERENCES users(user_id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
  student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
  student_number varchar(20) NOT NULL UNIQUE,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  grandfather_name varchar(50),
  gender varchar(10) CHECK (gender IN ('Male', 'Female')),
  date_of_birth date,
  phone_number varchar(15),
  region varchar(50),
  department_id integer REFERENCES departments(department_id),
  admission_year integer,
  current_year integer DEFAULT 1,
  dormitory varchar(100),
  campus varchar(100),
  building_no varchar(30),
  building_name varchar(100),
  floor varchar(20),
  dorm varchar(50),
  bed_no varchar(30),
  handicapped_case varchar(50),
  university_entrance_result numeric(7,2),
  status varchar(20) DEFAULT 'Active'
    CHECK (status IN ('Active', 'Graduated', 'Suspended', 'Withdrawn'))
);

CREATE TABLE IF NOT EXISTS instructors (
  instructor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
  employee_number varchar(20) NOT NULL UNIQUE,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  gender varchar(10) CHECK (gender IN ('Male', 'Female')),
  phone_number varchar(15),
  academic_rank varchar(30) NOT NULL
    CHECK (academic_rank IN ('Graduate Assistant', 'Lecturer', 'Assistant Professor', 'Associate Professor', 'Professor')),
  department_id integer REFERENCES departments(department_id),
  office_location varchar(50),
  hire_date date,
  is_hod boolean NOT NULL DEFAULT FALSE,
  hod_department_id integer REFERENCES departments(department_id)
);

CREATE TABLE IF NOT EXISTS courses (
  course_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_code varchar(15) NOT NULL UNIQUE,
  course_title varchar(150) NOT NULL,
  credit_hours integer NOT NULL,
  department_id integer NOT NULL REFERENCES departments(department_id),
  year_level integer NOT NULL,
  semester varchar(10) NOT NULL CHECK (semester IN ('I', 'II', 'Summer')),
  is_elective boolean DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS sections (
  section_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id integer NOT NULL REFERENCES courses(course_id),
  instructor_id integer REFERENCES instructors(instructor_id),
  academic_year varchar(10) NOT NULL,
  semester varchar(10) NOT NULL CHECK (semester IN ('I', 'II', 'Summer')),
  room varchar(20),
  schedule varchar(100),
  capacity integer DEFAULT 50
);

CREATE TABLE IF NOT EXISTS enrollments (
  enrollment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  section_id integer NOT NULL REFERENCES sections(section_id) ON DELETE CASCADE,
  academic_year varchar(10) NOT NULL,
  enrollment_date date DEFAULT CURRENT_DATE,
  status varchar(20) DEFAULT 'Enrolled'
    CHECK (status IN ('Enrolled', 'Dropped', 'Completed')),
  CONSTRAINT unique_enrollment UNIQUE (student_id, section_id, academic_year)
);

CREATE TABLE IF NOT EXISTS student_registration_requests (
  request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  academic_year varchar(10) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  student_note text,
  registrar_note text,
  submitted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by integer REFERENCES users(user_id) ON DELETE SET NULL,
  reviewed_at timestamp
);

CREATE TABLE IF NOT EXISTS student_registration_request_sections (
  request_id integer NOT NULL REFERENCES student_registration_requests(request_id) ON DELETE CASCADE,
  section_id integer NOT NULL REFERENCES sections(section_id) ON DELETE CASCADE,
  PRIMARY KEY (request_id, section_id)
);

CREATE TABLE IF NOT EXISTS grades (
  grade_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id integer NOT NULL UNIQUE REFERENCES enrollments(enrollment_id) ON DELETE CASCADE,
  assignment_mark numeric(5,2) DEFAULT 0,
  midterm_mark numeric(5,2) DEFAULT 0,
  final_mark numeric(5,2) DEFAULT 0,
  total_mark numeric(5,2) DEFAULT 0,
  letter_grade varchar(2),
  grade_point numeric(3,2),
  approval_status varchar(20) NOT NULL DEFAULT 'Approved'
    CHECK (approval_status IN ('Pending', 'Approved', 'Rejected')),
  finalized boolean NOT NULL DEFAULT FALSE,
  finalized_at timestamp,
  finalized_by integer REFERENCES users(user_id) ON DELETE SET NULL,
  recorded_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS attendance (
  attendance_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id integer NOT NULL REFERENCES enrollments(enrollment_id) ON DELETE CASCADE,
  attendance_date date NOT NULL,
  status varchar(10) NOT NULL CHECK (status IN ('Present', 'Absent', 'Late', 'Excused')),
  CONSTRAINT unique_attendance_day UNIQUE (enrollment_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS fields (
  field_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_name varchar(100) NOT NULL,
  department_id integer REFERENCES departments(department_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS field_selections (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  field_id integer NOT NULL REFERENCES fields(field_id),
  priority integer NOT NULL,
  CONSTRAINT unique_student_field UNIQUE (student_id, field_id),
  CONSTRAINT unique_student_priority UNIQUE (student_id, priority)
);

CREATE TABLE IF NOT EXISTS selection_results (
  result_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL UNIQUE REFERENCES students(student_id) ON DELETE CASCADE,
  field_id integer NOT NULL REFERENCES fields(field_id),
  department_id integer REFERENCES departments(department_id) ON DELETE SET NULL,
  status varchar(50) DEFAULT 'Assigned',
  announced_on date
);

CREATE TABLE IF NOT EXISTS sms_logs (
  sms_log_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer REFERENCES students(student_id) ON DELETE SET NULL,
  phone_number varchar(30),
  message text NOT NULL,
  status varchar(30) NOT NULL DEFAULT 'Pending',
  provider_response text,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS college_deans (
  dean_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
  employee_number varchar(20) NOT NULL UNIQUE,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  gender varchar(10) CHECK (gender IN ('Male', 'Female')),
  phone_number varchar(15),
  academic_rank varchar(30) NOT NULL
    CHECK (academic_rank IN ('Lecturer', 'Assistant Professor', 'Associate Professor', 'Professor')),
  college_id integer NOT NULL UNIQUE REFERENCES colleges(college_id) ON DELETE CASCADE,
  office_location varchar(50),
  hire_date date,
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS department_offerings (
  offering_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer NOT NULL REFERENCES departments(department_id),
  course_id integer NOT NULL REFERENCES courses(course_id),
  year_level integer NOT NULL,
  semester varchar(10) NOT NULL CHECK (semester IN ('I', 'II', 'Summer')),
  academic_year varchar(10) NOT NULL,
  is_active boolean NOT NULL DEFAULT TRUE,
  created_by integer NOT NULL REFERENCES users(user_id),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uniq_offering UNIQUE (department_id, course_id, academic_year, semester)
);

CREATE TABLE IF NOT EXISTS grade_upload_approvals (
  approval_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id integer NOT NULL UNIQUE REFERENCES sections(section_id) ON DELETE CASCADE,
  instructor_id integer NOT NULL REFERENCES instructors(instructor_id),
  college_id integer NOT NULL REFERENCES colleges(college_id),
  status varchar(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  dean_note text,
  submitted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by integer REFERENCES users(user_id) ON DELETE SET NULL,
  reviewed_at timestamp
);

CREATE TABLE IF NOT EXISTS dean_audit_logs (
  audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  college_id integer NOT NULL REFERENCES colleges(college_id) ON DELETE CASCADE,
  dean_user_id integer NOT NULL REFERENCES users(user_id),
  action varchar(40) NOT NULL,
  entity_type varchar(40) NOT NULL,
  entity_id integer,
  details jsonb,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS applicant_profiles (
  applicant_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  access_request_id integer NOT NULL UNIQUE REFERENCES access_requests(request_id) ON DELETE CASCADE,
  first_name varchar(50),
  last_name varchar(50),
  grandfather_name varchar(50),
  gender varchar(10) CHECK (gender IN ('Male', 'Female')),
  date_of_birth date,
  phone_number varchar(15),
  region varchar(50),
  high_school_name varchar(150),
  high_school_region varchar(50),
  university_entrance_result numeric(7,2),
  first_choice_department integer REFERENCES departments(department_id),
  second_choice_department integer REFERENCES departments(department_id),
  third_choice_department integer REFERENCES departments(department_id),
  transcript_url varchar(255),
  photo_url varchar(255),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alumni_requests (
  request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  request_type varchar(30) NOT NULL
    CHECK (request_type IN ('transcript', 'degree_verification', 'recommendation', 'replacement_id')),
  purpose text,
  status varchar(20) DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Processing', 'Ready', 'Delivered', 'Rejected')),
  admin_note text,
  requested_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ready_at timestamp,
  delivered_at timestamp
);

CREATE TABLE IF NOT EXISTS alumni_contact (
  student_id integer PRIMARY KEY REFERENCES students(student_id) ON DELETE CASCADE,
  current_email varchar(100),
  current_phone varchar(15),
  current_address text,
  employer varchar(150),
  job_title varchar(150),
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fee_types (
  fee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fee_name varchar(100) NOT NULL,
  fee_category varchar(20) NOT NULL
    CHECK (fee_category IN ('tuition', 'dormitory', 'library', 'registration', 'other')),
  amount numeric(10,2) NOT NULL,
  academic_year varchar(10) NOT NULL,
  semester varchar(10) NOT NULL CHECK (semester IN ('I', 'II', 'Summer')),
  is_mandatory boolean DEFAULT TRUE,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_invoices (
  invoice_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number varchar(30) NOT NULL UNIQUE,
  student_id integer NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
  fee_id integer NOT NULL REFERENCES fee_types(fee_id),
  academic_year varchar(10) NOT NULL,
  semester varchar(10) NOT NULL CHECK (semester IN ('I', 'II', 'Summer')),
  amount_due numeric(10,2) NOT NULL,
  amount_paid numeric(10,2) NOT NULL DEFAULT 0,
  status varchar(20) DEFAULT 'Unpaid'
    CHECK (status IN ('Unpaid', 'Partial', 'Paid', 'Waived', 'Overdue')),
  due_date date,
  issued_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_student_fee_period UNIQUE (student_id, fee_id, academic_year, semester)
);

CREATE TABLE IF NOT EXISTS payments (
  payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES student_invoices(invoice_id) ON DELETE CASCADE,
  amount numeric(10,2) NOT NULL,
  method varchar(20) NOT NULL
    CHECK (method IN ('Cash', 'Bank', 'Telebirr', 'CBE Birr', 'Waiver', 'Other')),
  reference_number varchar(100),
  receipt_number varchar(50) NOT NULL UNIQUE,
  paid_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  received_by integer NOT NULL REFERENCES users(user_id)
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_colleges_dean'
      AND conrelid = 'colleges'::regclass
  ) THEN
    ALTER TABLE colleges
      ADD CONSTRAINT fk_colleges_dean
      FOREIGN KEY (dean_user_id) REFERENCES users(user_id) ON DELETE SET NULL;
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS idx_access_requests_review
  ON access_requests (role, status, submitted_at);
CREATE INDEX IF NOT EXISTS idx_registration_requests_student
  ON student_registration_requests (student_id, submitted_at);
CREATE INDEX IF NOT EXISTS idx_registration_requests_review
  ON student_registration_requests (status, submitted_at);
CREATE INDEX IF NOT EXISTS idx_sms_logs_created ON sms_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_dean_audit_college
  ON dean_audit_logs (college_id, created_at);
CREATE INDEX IF NOT EXISTS idx_applicant_profiles_choices
  ON applicant_profiles (first_choice_department, second_choice_department, third_choice_department);
CREATE INDEX IF NOT EXISTS idx_alumni_requests_student_date
  ON alumni_requests (student_id, requested_at);
CREATE INDEX IF NOT EXISTS idx_alumni_requests_status
  ON alumni_requests (status, requested_at);
CREATE INDEX IF NOT EXISTS idx_fee_types_period
  ON fee_types (academic_year, semester);
CREATE INDEX IF NOT EXISTS idx_fee_types_category ON fee_types (fee_category);
CREATE INDEX IF NOT EXISTS idx_student_invoices_student
  ON student_invoices (student_id, status);
CREATE INDEX IF NOT EXISTS idx_student_invoices_period
  ON student_invoices (academic_year, semester, status);
CREATE INDEX IF NOT EXISTS idx_student_invoices_fee ON student_invoices (fee_id);
CREATE INDEX IF NOT EXISTS idx_payments_invoice_date ON payments (invoice_id, paid_at);
CREATE INDEX IF NOT EXISTS idx_payments_received_by ON payments (received_by, paid_at);

CREATE OR REPLACE FUNCTION set_alumni_contact_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS alumni_contact_updated_at ON alumni_contact;
CREATE TRIGGER alumni_contact_updated_at
BEFORE UPDATE ON alumni_contact
FOR EACH ROW EXECUTE FUNCTION set_alumni_contact_updated_at();

COMMIT;
